/* =============================================================
   SYNC SKINS — the app wears the same looks as the station page.

   The FunpostFM page defines every look ("Retro looks") as a set of
   --sk-* colours on body.skin-<name>. This copies those values (and
   the names and swatches from the page's look picker, and the
   Chattable palettes) into the app, so a look added to the page
   comes to the app with the next build:

     node sync-skins.js [page.html | https://…/index.html]

   With no argument it reads the page next door (../../live tool/
   esfores/index.html), else the live site. It also copies the
   listener scripts the app shares with the web (led-banner.js,
   rtc-client.js) from ../web/js.
   ============================================================= */
'use strict';
const fs = require('node:fs');
const path = require('node:path');

const UI = path.join(__dirname, 'ui');
const LOCAL = path.join(__dirname, '..', '..', 'live tool', 'esfores', 'index.html');
const SITE = 'https://esfores.neocities.org/index.html';

async function readPage(src) {
    if (/^https?:/i.test(src)) {
        const r = await fetch(src, { signal: AbortSignal.timeout(15000) });
        if (!r.ok) throw new Error(r.status + ' from ' + src);
        return r.text();
    }
    return fs.readFileSync(src, 'utf8');
}

/** body.skin-x { … } blocks whose selector is just that: the look's own values. */
function skinVars(html) {
    const css = (html.match(/<style>([\s\S]*?)<\/style>/) || [])[1] || '';
    const out = {};
    const re = /(^|\n)\s*body\.skin-([a-z0-9]+)\s*\{([^}]*)\}/g;
    let m;
    while ((m = re.exec(css))) {
        const name = m[2], body = m[3];
        for (const d of body.split(';')) {
            const kv = /^\s*(--(?:sk|lz)-[\w-]+)\s*:\s*([\s\S]+?)\s*$/.exec(d);
            if (kv) (out[name] = out[name] || {})[kv[1]] = kv[2].replace(/\s+/g, ' ');
        }
    }
    return out;
}

/** The look picker: [{ id, name, swatch }] in the page's order. */
function skinList(html) {
    const list = [];
    const re = /<button type="button" data-skin="([a-z0-9]*)"><span class="sw" style="background:([^"]+)"><\/span>([^<]+)<\/button>/g;
    let m;
    while ((m = re.exec(html))) list.push({ id: m[1], name: m[3].trim().replace(/&amp;/g, '&'), swatch: m[2] });
    return list;
}

/** const NAME = <literal>; — a template string or an object, read as data. */
function literal(html, name, open, close) {
    const at = html.indexOf('const ' + name + ' = ' + open);
    if (at < 0) return null;
    let i = html.indexOf(open, at), depth = 0;
    const start = i;
    if (open === '`') return html.slice(start + 1, html.indexOf('`', start + 1));
    for (; i < html.length; i++) {
        if (html[i] === open) depth++;
        else if (html[i] === close && --depth === 0) break;
    }
    // Our own page's object literal: plain data, no code.
    return Function('"use strict"; return (' + html.slice(start, i + 1) + ');')();
}

async function main() {
    const src = process.argv[2] || (fs.existsSync(LOCAL) ? LOCAL : SITE);
    let html;
    try { html = await readPage(src); }
    catch (e) { console.log('[skins] could not read', src, '—', e.message, '(keeping the current copy)'); return copyShared(); }

    const vars = skinVars(html), list = skinList(html);
    if (!list.length || !Object.keys(vars).length) { console.log('[skins] no looks found in', src); return copyShared(); }

    const css = ['/* Generated by sync-skins.js from ' + path.basename(src) + ' — do not edit; edit the page and sync. */'];
    for (const [name, v] of Object.entries(vars)) {
        css.push('body.skin-' + name + ' {\n' + Object.entries(v).map(([k, x]) => '    ' + k + ': ' + x + ';').join('\n') + '\n}');
    }
    fs.writeFileSync(path.join(UI, 'skins.css'), css.join('\n') + '\n');

    const data = {
        skins: list.filter(s => !s.id || vars[s.id]),
        chatLooks: literal(html, 'CHAT_LOOKS', '{', '}') || {},
        chattableCss: literal(html, 'CHATTABLE_CSS', '`') || ''
    };
    fs.writeFileSync(path.join(UI, 'look-data.js'),
        '/* Generated by sync-skins.js — the station page\'s looks, for the app. */\nwindow.LOOKS = ' + JSON.stringify(data, null, 1) + ';\n');
    console.log('[skins]', data.skins.length, 'looks,', Object.keys(data.chatLooks).length, 'chat palettes from', src);
    copyShared();
}

function copyShared() {
    const from = path.join(__dirname, '..', 'web', 'js'), to = path.join(UI, 'vendor');
    fs.mkdirSync(to, { recursive: true });
    for (const f of ['led-banner.js', 'rtc-client.js']) {
        try { fs.copyFileSync(path.join(from, f), path.join(to, f)); } catch (e) { console.log('[skins] could not copy', f, e.message); }
    }
}

main();
